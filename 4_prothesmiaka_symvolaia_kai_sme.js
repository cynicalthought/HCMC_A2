function renderQuestion() {
    if (typeof currentQuestionIndex === 'undefined') {
        window.currentQuestionIndex = 0;
    }
    
    const q = module4Data.data[currentQuestionIndex];
    const questionTextEl = document.getElementById('questionText');
    
    if (questionTextEl) {
        let htmlContent = q.question;
        
        if (q.image) {
            htmlContent += `<br><img src="${q.image}" alt="Question Graph" style="max-width: 100%; height: auto; margin: 15px 0; display: block;" />`;
        } else {
            const existingImg = questionTextEl.querySelector('img');
            if (existingImg) existingImg.remove();
        }
        
        questionTextEl.innerHTML = htmlContent;
    }
}